CREATE OR REPLACE VIEW V_ORDER_SUMMARY AS
SELECT
    o.ID AS ORDER_ID,
    c.NAME AS CUSTOMER_NAME,
    o.STATUS,
    o.TOTAL_AMOUNT
FROM ORDERS o
JOIN CUSTOMERS c ON c.ID = o.CUSTOMER_ID;

CREATE OR REPLACE VIEW V_ORDER_DETAIL AS
SELECT
    o.ID AS ORDER_ID,
    o.ORDER_NO,
    o.STATUS,
    o.ORDER_DATE,
    c.ID AS CUSTOMER_ID,
    c.NAME AS CUSTOMER_NAME,
    p.ID AS PRODUCT_ID,
    p.SKU,
    p.NAME AS PRODUCT_NAME,
    oi.QUANTITY,
    oi.UNIT_PRICE,
    oi.QUANTITY * oi.UNIT_PRICE AS LINE_AMOUNT
FROM ORDERS o
JOIN CUSTOMERS c ON c.ID = o.CUSTOMER_ID
JOIN ORDER_ITEMS oi ON oi.ORDER_ID = o.ID
JOIN PRODUCTS p ON p.ID = oi.PRODUCT_ID;

CREATE OR REPLACE VIEW V_CUSTOMER_LIFETIME_VALUE AS
SELECT
    c.ID AS CUSTOMER_ID,
    c.NAME AS CUSTOMER_NAME,
    COUNT(DISTINCT o.ID) AS ORDER_COUNT,
    COALESCE(SUM(o.TOTAL_AMOUNT), 0) AS TOTAL_AMOUNT
FROM CUSTOMERS c
LEFT JOIN ORDERS o ON o.CUSTOMER_ID = c.ID
GROUP BY c.ID, c.NAME;

CREATE OR REPLACE VIEW V_PRODUCT_SALES AS
SELECT
    p.ID AS PRODUCT_ID,
    p.SKU,
    p.NAME AS PRODUCT_NAME,
    COALESCE(SUM(oi.QUANTITY), 0) AS TOTAL_QUANTITY,
    COALESCE(SUM(oi.QUANTITY * oi.UNIT_PRICE), 0) AS TOTAL_AMOUNT
FROM PRODUCTS p
LEFT JOIN ORDER_ITEMS oi ON oi.PRODUCT_ID = p.ID
GROUP BY p.ID, p.SKU, p.NAME;

CREATE OR REPLACE FUNCTION FN_CUSTOMER_ORDER_COUNT(P_CUSTOMER_ID INT) RETURN INT AS
    V_COUNT INT;
BEGIN
    SELECT COUNT(*) INTO V_COUNT FROM ORDERS WHERE CUSTOMER_ID = P_CUSTOMER_ID;
    RETURN V_COUNT;
END;
/

CREATE OR REPLACE FUNCTION FN_CUSTOMER_TOTAL_AMOUNT(P_CUSTOMER_ID INT) RETURN DECIMAL(18, 2) AS
    V_TOTAL DECIMAL(18, 2);
BEGIN
    SELECT COALESCE(SUM(TOTAL_AMOUNT), 0) INTO V_TOTAL FROM ORDERS WHERE CUSTOMER_ID = P_CUSTOMER_ID;
    RETURN V_TOTAL;
END;
/

CREATE OR REPLACE PROCEDURE P_REFRESH_ORDER_STATS AS
BEGIN
    NULL;
END;
/

CREATE OR REPLACE TRIGGER TRG_ORDERS_AUDIT
AFTER UPDATE OF STATUS, TOTAL_AMOUNT ON ORDERS
FOR EACH ROW
BEGIN
    INSERT INTO ORDER_AUDIT (
        ID,
        ORDER_ID,
        OLD_STATUS,
        NEW_STATUS,
        OLD_TOTAL_AMOUNT,
        NEW_TOTAL_AMOUNT
    ) VALUES (
        ORDER_AUDIT_SEQ.NEXTVAL,
        :OLD.ID,
        :OLD.STATUS,
        :NEW.STATUS,
        :OLD.TOTAL_AMOUNT,
        :NEW.TOTAL_AMOUNT
    );
END;
/

COMMIT;
