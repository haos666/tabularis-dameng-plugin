CREATE TABLE CUSTOMERS (
    ID INT NOT NULL,
    NAME VARCHAR(80) NOT NULL,
    CITY VARCHAR(40),
    SEGMENT VARCHAR(30),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_CUSTOMERS PRIMARY KEY (ID)
);

CREATE TABLE PRODUCTS (
    ID INT NOT NULL,
    SKU VARCHAR(40) NOT NULL,
    NAME VARCHAR(100) NOT NULL,
    CATEGORY VARCHAR(40),
    PRICE DECIMAL(18, 2) NOT NULL,
    CONSTRAINT PK_PRODUCTS PRIMARY KEY (ID)
);

CREATE TABLE ORDERS (
    ID INT NOT NULL,
    CUSTOMER_ID INT NOT NULL,
    ORDER_NO VARCHAR(40) NOT NULL,
    STATUS VARCHAR(20),
    ORDER_DATE DATE,
    TOTAL_AMOUNT DECIMAL(18, 2),
    CONSTRAINT PK_ORDERS PRIMARY KEY (ID)
);

CREATE TABLE ORDER_ITEMS (
    ID INT NOT NULL,
    ORDER_ID INT NOT NULL,
    PRODUCT_ID INT NOT NULL,
    QUANTITY INT NOT NULL,
    UNIT_PRICE DECIMAL(18, 2) NOT NULL,
    CONSTRAINT PK_ORDER_ITEMS PRIMARY KEY (ID)
);

CREATE TABLE ORDER_AUDIT (
    ID INT NOT NULL,
    ORDER_ID INT NOT NULL,
    OLD_STATUS VARCHAR(20),
    NEW_STATUS VARCHAR(20),
    OLD_TOTAL_AMOUNT DECIMAL(18, 2),
    NEW_TOTAL_AMOUNT DECIMAL(18, 2),
    CHANGED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_ORDER_AUDIT PRIMARY KEY (ID)
);

CREATE TABLE T_WRITE_TEST (
    ID INT IDENTITY(1,1) NOT NULL,
    NAME VARCHAR(80),
    SCORE INT,
    NOTE VARCHAR(200),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_T_WRITE_TEST PRIMARY KEY (ID)
);

CREATE TABLE T_LOB_TEST (
    ID INT IDENTITY(1,1) NOT NULL,
    NAME VARCHAR(80),
    PAYLOAD_BLOB BLOB,
    PAYLOAD_BIN VARBINARY(200),
    PAYLOAD_CLOB CLOB,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_T_LOB_TEST PRIMARY KEY (ID)
);

CREATE TABLE T_DEFAULT_TEST (
    ID INT IDENTITY(1,1) NOT NULL,
    STATUS VARCHAR(20) DEFAULT 'NEW' NOT NULL,
    SCORE INT DEFAULT 0,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_T_DEFAULT_TEST PRIMARY KEY (ID)
);

